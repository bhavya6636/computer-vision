class ResidualBlock(nn.Module):
    def __init__(self, in_channels, out_channels):
        super().__init__()

        self.conv1 = nn.Conv2d(in_channels, out_channels, 3, padding=1)
        self.bn1 = nn.BatchNorm2d(out_channels)

        self.conv2 = nn.Conv2d(out_channels, out_channels, 3, padding=1)
        self.bn2 = nn.BatchNorm2d(out_channels)

        self.relu = nn.ReLU(inplace=True)

        if in_channels != out_channels:
            self.shortcut = nn.Conv2d(in_channels, out_channels, 1)
        else:
            self.shortcut = nn.Identity()

    def forward(self, x):
        identity = self.shortcut(x)

        out = self.relu(self.bn1(self.conv1(x)))
        out = self.bn2(self.conv2(out))

        out = out + identity
        out = self.relu(out)

        return out

class AttentionGate(nn.Module):
    def __init__(self, gating_channels, skip_channels, inter_channels):
        super().__init__()

        self.gating = nn.Conv2d(gating_channels, inter_channels, 1)
        self.skip = nn.Conv2d(skip_channels, inter_channels, 1)

        self.attention = nn.Sequential(
            nn.ReLU(inplace=True),
            nn.Conv2d(inter_channels, 1, 1),
            nn.Sigmoid()
        )

    def forward(self, gating, skip):
        g = self.gating(gating)
        x = self.skip(skip)

        attention_map = self.attention(g + x)

        return skip * attention_map

class ResidualAttentionUNet(nn.Module):
    def __init__(self):
        super().__init__()

        self.enc1 = ResidualBlock(3, 64)
        self.enc2 = ResidualBlock(64, 128)
        self.enc3 = ResidualBlock(128, 256)
        self.enc4 = ResidualBlock(256, 512)

        self.pool = nn.MaxPool2d(2)

        self.bottleneck = ResidualBlock(512, 1024)

        self.up4 = nn.ConvTranspose2d(1024, 512, 2, stride=2)
        self.att4 = AttentionGate(512, 512, 256)
        self.dec4 = ResidualBlock(1024, 512)

        self.up3 = nn.ConvTranspose2d(512, 256, 2, stride=2)
        self.att3 = AttentionGate(256, 256, 128)
        self.dec3 = ResidualBlock(512, 256)

        self.up2 = nn.ConvTranspose2d(256, 128, 2, stride=2)
        self.att2 = AttentionGate(128, 128, 64)
        self.dec2 = ResidualBlock(256, 128)

        self.up1 = nn.ConvTranspose2d(128, 64, 2, stride=2)
        self.att1 = AttentionGate(64, 64, 32)
        self.dec1 = ResidualBlock(128, 64)

        self.output = nn.Conv2d(64, 1, 1)

    def forward(self, x):

        e1 = self.enc1(x)
        e2 = self.enc2(self.pool(e1))
        e3 = self.enc3(self.pool(e2))
        e4 = self.enc4(self.pool(e3))

        b = self.bottleneck(self.pool(e4))

        d4 = self.up4(b)
        a4 = self.att4(d4, e4)
        d4 = torch.cat([d4, a4], dim=1)
        d4 = self.dec4(d4)

        d3 = self.up3(d4)
        a3 = self.att3(d3, e3)
        d3 = torch.cat([d3, a3], dim=1)
        d3 = self.dec3(d3)

        d2 = self.up2(d3)
        a2 = self.att2(d2, e2)
        d2 = torch.cat([d2, a2], dim=1)
        d2 = self.dec2(d2)

        d1 = self.up1(d2)
        a1 = self.att1(d1, e1)
        d1 = torch.cat([d1, a1], dim=1)
        d1 = self.dec1(d1)

        return self.output(d1)

