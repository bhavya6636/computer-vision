import torch

def calculate_metrics(model, loader, device, threshold=0.5):
    model.eval()

    total_dice = 0
    total_iou = 0
    total_precision = 0
    count = 0

    with torch.no_grad():

        for images, masks in loader:

            images = images.to(device)
            masks = masks.to(device)

            outputs = torch.sigmoid(model(images))
            predictions = (outputs > threshold).float()

            predictions = predictions.view(predictions.size(0), -1)
            masks = masks.view(masks.size(0), -1)

            intersection = (predictions * masks).sum(dim=1)

            prediction_area = predictions.sum(dim=1)
            mask_area = masks.sum(dim=1)

            union = prediction_area + mask_area - intersection

            true_positive = intersection
            false_positive = (predictions * (1 - masks)).sum(dim=1)

            dice = (2 * intersection + 1e-7) / (
                prediction_area + mask_area + 1e-7
            )

            iou = (intersection + 1e-7) / (union + 1e-7)

            precision = (true_positive + 1e-7) / (
                true_positive + false_positive + 1e-7
            )

            total_dice += dice.sum().item()
            total_iou += iou.sum().item()
            total_precision += precision.sum().item()

            count += images.size(0)

    return (
        total_dice / count,
        total_iou / count,
        total_precision / count
    )


